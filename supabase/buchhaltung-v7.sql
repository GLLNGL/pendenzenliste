-- ==========================================================================
-- Buchhaltung (v7): eigene Kreditoren- und Debitorenrechnungen. Mehrfach ausfuehrbar.
-- Der Beleg (PDF) liegt nur im OneDrive-Ordner (EST Controlling › Kreditoren|Debitoren › Jahr);
-- hier stehen nur die Angaben fuer Liste und Liquiditaetsplan.
-- ==========================================================================
create table if not exists public.belege (
  id              bigint generated by default as identity primary key,
  art             text not null check (art in ('kreditor', 'debitor')),
  partner         text not null,            -- Kreditor bzw. Debitor
  rechnungsnummer text,
  rechnungsdatum  date,
  faelligkeit     date,
  betrag          numeric(12, 2),           -- Rechnungsbetrag inkl. MWST
  waehrung        text not null default 'CHF',
  bezahlt_am      date,
  dateiname       text,
  ablage_pfad     text,                     -- Pfad in OneDrive (Grundordner\…\Datei.pdf)
  notiz           text,
  erstellt_am     timestamptz not null default now()
);
create index if not exists idx_belege_art_faelligkeit on public.belege (art, faelligkeit);

alter table public.belege enable row level security;
drop policy if exists team_voller_zugriff on public.belege;
create policy team_voller_zugriff on public.belege
  for all using (auth.uid() is not null) with check (auth.uid() is not null);

-- Einstellungen: Ablage (Mandant + Unterordner) und Kontostand fuer den Liquiditaetsplan.
insert into public.buero_einstellungen (schluessel, wert) values
  ('buchhaltung', jsonb_build_object(
    'mandantId', null, 'ordnerKreditoren', 'Kreditoren', 'ordnerDebitoren', 'Debitoren', 'proJahr', true,
    'kontostand', null, 'kontostandDatum', null))
on conflict (schluessel) do nothing;
