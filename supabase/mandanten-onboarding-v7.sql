-- ==========================================================================
-- Dateien, Ablage und Onboarding (v7). Mehrfach ausfuehrbar.
--
-- 1. Dateien: Anhaenge der Auftrags-Mails und Vorlagen der Onboarding-Unterlagen liegen im
--    Supabase-Speicher (Bucket "dateien", nicht oeffentlich). Die Tabelle merkt sich, zu welcher
--    Pendenz / welchem Mandanten eine Datei gehoert und ob sie schon abgelegt wurde.
-- 2. Ablage: Grundordner einmal in den Einstellungen (Schluessel "ablage"), pro Mandant nur noch
--    der Ordnername (mandanten.ablage_ordner). Der volle Pfad/Link wird daraus zusammengesetzt;
--    ablage_pfad/ablage_link bleiben als Abweichung fuer Sonderfaelle.
-- 3. Onboarding: Katalog der Unterlagen (DL-Vertrag, Vollmacht, EBICS ...) und pro Mandant ein
--    Onboarding mit Checkliste (was mitgesendet, was unterschrieben zurueck ist).
-- ==========================================================================

-- 1. Dateien -----------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('dateien', 'dateien', false)
on conflict (id) do nothing;

drop policy if exists dateien_team on storage.objects;
create policy dateien_team on storage.objects
  for all to authenticated
  using (bucket_id = 'dateien')
  with check (bucket_id = 'dateien');

create table if not exists public.dateien (
  id            bigint generated by default as identity primary key,
  pendenz_id    bigint references public.pendenzen(id) on delete cascade,
  mandant_id    bigint references public.mandanten(id) on delete set null,
  dateiname     text not null,
  typ           text,
  groesse       integer,
  speicherpfad  text not null unique,
  quelle        text not null default 'upload' check (quelle in ('mail', 'upload', 'vorlage')),
  abgelegt_am   timestamptz,
  erstellt_am   timestamptz not null default now()
);
create index if not exists idx_dateien_pendenz on public.dateien (pendenz_id);
create index if not exists idx_dateien_mandant on public.dateien (mandant_id);

alter table public.dateien enable row level security;
drop policy if exists team_voller_zugriff on public.dateien;
create policy team_voller_zugriff on public.dateien
  for all using (auth.uid() is not null) with check (auth.uid() is not null);

-- 2. Ablage ------------------------------------------------------------------
alter table public.mandanten add column if not exists ablage_ordner text;

insert into public.buero_einstellungen (schluessel, wert) values
  ('ablage', jsonb_build_object('grundPfad', '', 'grundLink', ''))
on conflict (schluessel) do nothing;

-- 3. Onboarding --------------------------------------------------------------
create table if not exists public.onboarding_unterlagen (
  id            bigint generated by default as identity primary key,
  name          text not null unique,
  beschreibung  text,
  zurueck       boolean not null default true,   -- muss unterschrieben zurueckkommen
  aktiv         boolean not null default true,
  reihenfolge   integer not null default 0,
  datei_id      bigint references public.dateien(id) on delete set null,  -- Vorlage zum Mitsenden
  erstellt_am   timestamptz not null default now()
);

insert into public.onboarding_unterlagen (name, beschreibung, zurueck, reihenfolge) values
  ('Dienstleistungsvertrag', 'DL-Vertrag, unterschrieben zurück', true, 10),
  ('Vollmacht', 'Vollmacht für Behörden und Banken, unterschrieben zurück', true, 20),
  ('Bestellung EBICS-Vertrag', 'Bestellung EBICS bei der Bank des Mandanten', true, 30)
on conflict (name) do nothing;

create table if not exists public.mandant_onboarding (
  id                bigint generated by default as identity primary key,
  mandant_id        bigint not null unique references public.mandanten(id) on delete cascade,
  offerte_id        bigint references public.offerten(id) on delete set null,
  gestartet_am      date not null default current_date,
  -- Checkliste: [{ unterlageId, name, zurueck, mitsenden, gesendetAm, erhaltenAm }]
  unterlagen        jsonb not null default '[]'::jsonb,
  mail_gesendet_am  timestamptz,
  mail_an           text,
  abgeschlossen_am  date,
  notiz             text
);

insert into public.buero_einstellungen (schluessel, wert) values
  ('onboarding', jsonb_build_object(
    'mailBetreff', 'Willkommen bei {firma} – Unterlagen zur Mandatseröffnung',
    'mailText', E'Guten Tag {ansprechperson}\n\nBesten Dank für Ihr Vertrauen. Für die Eröffnung des Mandats {mandant} erhalten Sie im Anhang folgende Unterlagen:\n\n{unterlagen}\n\nBitte senden Sie uns die unterschriebenen Dokumente zurück. Für Fragen stehen wir Ihnen gerne zur Verfügung.\n\nFreundliche Grüsse\n{bearbeiter}\n{firma}'))
on conflict (schluessel) do nothing;

alter table public.onboarding_unterlagen enable row level security;
alter table public.mandant_onboarding    enable row level security;
drop policy if exists team_voller_zugriff on public.onboarding_unterlagen;
create policy team_voller_zugriff on public.onboarding_unterlagen
  for all using (auth.uid() is not null) with check (auth.uid() is not null);
drop policy if exists team_voller_zugriff on public.mandant_onboarding;
create policy team_voller_zugriff on public.mandant_onboarding
  for all using (auth.uid() is not null) with check (auth.uid() is not null);
