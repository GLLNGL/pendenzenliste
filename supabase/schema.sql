create table if not exists public.pendenzen (
  id                          bigint generated by default as identity primary key,
  -- "Naechster Schritt" (Verb + Objekt) -- in der Oberflaeche so beschriftet, technisch weiter
  -- "titel", damit alle bestehenden Abfragen/Views unveraendert bleiben.
  titel                       text not null,
  mandant_id                  bigint references public.mandanten(id) on delete set null,
  beschreibung                text,
  -- "Frist" in der Oberflaeche.
  faelligkeit                 date not null,
  -- A = harte Frist in <= 5 Arbeitstagen oder Mandant blockiert, B = wichtig/nicht dringend,
  -- C = dringend/wenig Wert (buendeln/delegieren).
  prioritaet                  text not null default 'B' check (prioritaet in ('A', 'B', 'C')),
  status                      text not null default 'Offen' check (status in ('Offen', 'In Arbeit', 'Warten auf', 'Später', 'Erledigt')),
  -- Veraltet seit Etappe 1 (ersetzt durch aufwand_minuten), bleibt als Referenz erhalten.
  aufwand_stunden             numeric,
  erstellt_am                 timestamptz not null default now(),
  erledigt_am                 date,
  warte_seit                  date,
  -- "Nachfassdatum" bei Status "Warten auf" (Pflicht, siehe Constraint unten).
  wiedervorlage               date,
  regel_id                    bigint references public.wiederkehr_regeln(id) on delete set null,
  perioden_schluessel         text,
  uebergeordnete_pendenz_id   bigint references public.pendenzen(id) on delete cascade,
  bearbeiter_id               bigint references public.mitarbeitende(id) on delete set null,
  -- "Eingang" -- schnell unterwegs erfasste Notizen (Mobil-Erfassen), die erst noch einem
  -- Mandanten/einer echten Faelligkeit zugeordnet werden muessen, bevor sie in Cockpit/Alle
  -- Pendenzen/Mandanten auftauchen. false = liegt im Eingang, true = eingeplant (normal
  -- sichtbar). Wird beim vollstaendigen Bearbeiten/Speichern automatisch auf true gesetzt.
  geplant                     boolean not null default true,
  -- Bearbeitungstag -- eigenstaendiges, von der Faelligkeit UNABHAENGIGES Planungsdatum: wann
  -- als Naechstes an dieser Pendenz gearbeitet werden soll (z.B. schon am 20.10. anfangen,
  -- obwohl die echte Faelligkeit erst der 30.10. ist). Bewusst ein zweites Datumsfeld statt die
  -- Faelligkeit zu verschieben -- siehe "Cockpit neu"-Planung: Muss-Datum und Planungsdatum
  -- sollen getrennt bleiben.
  bearbeitungstag             date,
  -- Etappe 1 (Arbeitsprozess) -- Beschreibung siehe Migrationsblock unten.
  harte_frist                 boolean not null default false,
  aufwand_minuten             integer check (aufwand_minuten in (15, 30, 60, 120)),
  warten_auf_person           text,
  block                       text not null default 'Sonstiges'
                                check (block in ('Zahlungen', 'Lohn', 'MWST', 'Abschluss', 'Debitoren', 'Admin', 'Sonstiges')),
  reihenfolge                 integer,
  zuletzt_geaendert_am        timestamptz not null default now()
);

-- "create table if not exists" legt neue Spalten nur bei einer NEUEN Tabelle an -- bei einer
-- bereits bestehenden pendenzen-Tabelle (wie hier, nach der urspruenglichen Migration) bewirkt
-- es nichts. Darum zusaetzlich explizit nachtragen, idempotent dank "if not exists".
alter table public.pendenzen add column if not exists bearbeitungstag date;

-- --------------------------------------------------------------------------
-- Etappe 1 (Arbeitsprozess) -- Migration bestehender Daten.
--
-- Laeuft in EINEM Block, damit bei einem Fehler nichts halb migriert zurueckbleibt (der
-- SQL-Editor fuehrt einen DO-Block als Ganzes aus, ein Fehler rollt ihn komplett zurueck).
-- Jeder Teilschritt prueft selbst, ob er schon gelaufen ist (Spalte existiert bereits bzw.
-- keine Zeile mit altem Wert mehr) -- erneutes Ausfuehren veraendert keine Daten.
--
-- WICHTIG: Der Status-Kaskaden-Trigger (weiter unten) reagiert u.a. auf Aenderungen an status
-- und prioritaet und wuerde beim Umschreiben einer Hauptaufgabe alle ihre Teilaufgaben auf
-- Offen/Erledigt zuruecksetzen. Darum wird er waehrend der Migration ausgeschaltet.
-- --------------------------------------------------------------------------

do $$
declare
  trigger_vorhanden boolean;
begin
  select exists (select 1 from pg_trigger where tgname = 'trg_pendenzen_status_update' and tgrelid = 'public.pendenzen'::regclass)
    into trigger_vorhanden;
  if trigger_vorhanden then
    execute 'alter table public.pendenzen disable trigger trg_pendenzen_status_update';
  end if;

  -- Prioritaet Hoch/Mittel/Tief -> A/B/C.
  alter table public.pendenzen drop constraint if exists pendenzen_prioritaet_check;
  update public.pendenzen set prioritaet = case prioritaet when 'Hoch' then 'A' when 'Mittel' then 'B' when 'Tief' then 'C' end
    where prioritaet in ('Hoch', 'Mittel', 'Tief');
  alter table public.pendenzen alter column prioritaet set default 'B';
  alter table public.pendenzen add constraint pendenzen_prioritaet_check check (prioritaet in ('A', 'B', 'C'));

  -- Status: "Warte auf Kunde"/"Warte intern" -> "Warten auf" mit Person + Nachfassdatum
  -- (beides ab jetzt Pflicht). Person: Mandantenname bzw. "Kunde"/"intern"; Nachfassdatum:
  -- bisherige Wiedervorlage, sonst "warte seit" + 7 Tage, sonst heute.
  alter table public.pendenzen add column if not exists warten_auf_person text;
  alter table public.pendenzen drop constraint if exists pendenzen_status_check;
  update public.pendenzen p
    set warten_auf_person = coalesce(p.warten_auf_person,
          case when p.status = 'Warte intern' then 'intern'
               else coalesce((select m.name from public.mandanten m where m.id = p.mandant_id), 'Kunde') end),
        wiedervorlage = coalesce(p.wiedervorlage, p.warte_seit + 7, current_date),
        status = 'Warten auf'
    where p.status in ('Warte auf Kunde', 'Warte intern');
  alter table public.pendenzen add constraint pendenzen_status_check
    check (status in ('Offen', 'In Arbeit', 'Warten auf', 'Später', 'Erledigt'));
  alter table public.pendenzen drop constraint if exists pendenzen_warten_auf_pflicht;
  alter table public.pendenzen add constraint pendenzen_warten_auf_pflicht
    check (status <> 'Warten auf' or (nullif(btrim(warten_auf_person), '') is not null and wiedervorlage is not null));

  -- Kennzeichen "harte Frist" (Behoerden-/Zahlungsfristen). Bestehende: nein.
  alter table public.pendenzen add column if not exists harte_frist boolean not null default false;

  -- Aufwand in Minuten (15/30/60/120) -- aus den bisherigen Stunden auf den naechsten Wert
  -- gerundet. aufwand_stunden bleibt unveraendert stehen.
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'pendenzen' and column_name = 'aufwand_minuten') then
    alter table public.pendenzen add column aufwand_minuten integer check (aufwand_minuten in (15, 30, 60, 120));
    update public.pendenzen set aufwand_minuten = case
        when aufwand_stunden * 60 <= 22.5 then 15
        when aufwand_stunden * 60 <= 45 then 30
        when aufwand_stunden * 60 <= 90 then 60
        else 120
      end
      where aufwand_stunden is not null;
  end if;

  -- Block -- per Stichwort aus dem Titel zugeordnet, sonst "Sonstiges". Teilaufgaben uebernehmen
  -- den Block ihres Projekts (sofern dieses einen erkannt hat), damit ein Projekt beisammen
  -- bleibt (z.B. "Abstimmung MWSt" innerhalb eines Jahresabschlusses -> Abschluss).
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'pendenzen' and column_name = 'block') then
    alter table public.pendenzen add column block text not null default 'Sonstiges'
      check (block in ('Zahlungen', 'Lohn', 'MWST', 'Abschluss', 'Debitoren', 'Admin', 'Sonstiges'));
    update public.pendenzen set block = case
        when titel ~* '(mwst|mehrwertsteuer)' then 'MWST'
        when titel ~* '(lohn|löhne|salär|ahv|bvg|suva|sva|qst|quellensteuer|kizu|sozialversicherung|gastrosocial|bonus|mitarbeitende anmelden)' then 'Lohn'
        when titel ~* '(zahlung|zahllauf|kreditor|ebics)' then 'Zahlungen'
        when titel ~* '(mahn|debitor|inkasso|betreibung|rechnung versenden|faktur)' then 'Debitoren'
        when titel ~* '(abschluss|jahresrechnung|bilanz|reporting|steuererkl|steuerveranlag|steuerauflag)' then 'Abschluss'
        when titel ~* '(ordnerstruktur|offerte|angebot|ablage|admin)' then 'Admin'
        else 'Sonstiges'
      end;
    update public.pendenzen kind set block = eltern.block
      from public.pendenzen eltern
      where kind.uebergeordnete_pendenz_id = eltern.id and eltern.block <> 'Sonstiges';
  end if;

  -- Reihenfolge innerhalb eines Projekts -- bestehende Teilaufgaben nach Frist, dann ID
  -- durchnummeriert. Status bleiben bewusst unveraendert (Projekt-Logik greift erst bei der
  -- naechsten Aenderung, Etappe 2).
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'pendenzen' and column_name = 'reihenfolge') then
    alter table public.pendenzen add column reihenfolge integer;
    update public.pendenzen p set reihenfolge = nummeriert.nr
      from (select id, row_number() over (partition by uebergeordnete_pendenz_id order by faelligkeit, id) as nr
            from public.pendenzen where uebergeordnete_pendenz_id is not null) nummeriert
      where p.id = nummeriert.id;
  end if;

  -- Zuletzt geaendert -- Startwert: juengste bekannte Aktivitaet (Erstellung, Erledigung,
  -- Fortschrittsnotiz, E-Mail). Bewusst NICHT "jetzt": sonst waere nach der Migration alles
  -- "frisch geaendert"; bewusst auch nicht nur erstellt_am: sonst erschiene fast alles sofort
  -- als "seit ueber 14 Tagen unveraendert".
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'pendenzen' and column_name = 'zuletzt_geaendert_am') then
    alter table public.pendenzen add column zuletzt_geaendert_am timestamptz;
    update public.pendenzen p set zuletzt_geaendert_am = greatest(
        p.erstellt_am,
        p.erledigt_am::timestamptz,
        (select max(n.erstellt_am) from public.pendenz_notizen n where n.pendenz_id = p.id),
        (select max(e.gesendet_am) from public.pendenz_emails e where e.pendenz_id = p.id)
      );
    alter table public.pendenzen alter column zuletzt_geaendert_am set default now();
    alter table public.pendenzen alter column zuletzt_geaendert_am set not null;
  end if;

  if trigger_vorhanden then
    execute 'alter table public.pendenzen enable trigger trg_pendenzen_status_update';
  end if;
end $$;

