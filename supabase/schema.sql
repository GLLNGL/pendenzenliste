create table if not exists public.wiederkehr_regeln (
  id                  bigint generated by default as identity primary key,
  titel_vorlage       text not null,
  mandant_id          bigint references public.mandanten(id) on delete set null,
  rhythmus            text not null check (rhythmus in ('woechentlich', '14-taeglich', 'monatlich', 'quartalsweise', 'halbjaehrlich', 'jaehrlich')),
  faelligkeit_typ     text not null,
  faelligkeit_config  jsonb not null default '{}'::jsonb,
  vorlauf_tage        integer not null default 0,
  aktiv               boolean not null default true,
  -- Etappe 4 (Arbeitsprozess) -- Beschreibung siehe Migrationsblock unten.
  typ                 text not null default 'Sonstiges'
                        check (typ in ('Zahlungslauf', 'Lohnlauf', 'MWST', 'Mahnlauf', 'Jahresabschluss', 'Sonstiges')),
  block               text not null default 'Sonstiges'
                        check (block in ('Zahlungen', 'Lohn', 'MWST', 'Abschluss', 'Debitoren', 'Admin', 'Sonstiges')),
  vorlauf_einheit     text not null default 'tage' check (vorlauf_einheit in ('tage', 'arbeitstage')),
