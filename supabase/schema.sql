-- Pendenzenliste -- Supabase-Schema (Postgres). Portierung von backend/src/schema.sql.
--
-- Handgepflegt und idempotent (kein Migrations-Tool), gleiches Muster wie im Schwesterprojekt
-- "CrossFit Tracker" (supabase/schema.sql). Einmal im Supabase SQL-Editor ausfuehren; danach
-- bei Aenderungen erneut ausfuehren (CREATE ... IF NOT EXISTS / CREATE OR REPLACE ueberall).
-- Einmalige Daten-Migrationen (z.B. "Etappe 1" weiter unten) laufen nur beim ersten Mal, wenn
-- die betreffende Spalte noch fehlt -- ein erneutes Ausfuehren ueberschreibt keine Daten.
--
-- WICHTIGE ABWEICHUNG vom CrossFit-Tracker-Vorbild: das dort verwendete RLS-Muster
-- "auth.uid() = user_id" (jede Person sieht nur eigene Zeilen) passt hier NICHT -- die
-- Pendenzenliste ist eine Team-App, alle angemeldeten Mitarbeitenden teilen sich dieselben
-- Mandanten/Pendenzen. Policies unten pruefen darum nur "ist ueberhaupt angemeldet"
-- (auth.uid() is not null), nicht eine Zeilen-Eigentuemerschaft.

-- ==========================================================================
-- mitarbeitende -- eigene ID (nicht an auth.users gebunden), mit OPTIONALER Verknuepfung zu
-- einem Login-Konto. Anders als beim ersten Entwurf bewusst NICHT id = auth.users.id: die
-- bisherige App erlaubt Mitarbeitende OHNE Login (nur als Bearbeiter/in zuweisbar, siehe
-- Team.jsx "kein Login"-Tag) -- das bleibt so moeglich. Ersetzt die bisherige eigene
-- Session-/Passwort-Verwaltung (sitzungen, passwort_hash) durch Supabase Auth, aber nur fuer
-- Personen, die tatsaechlich ein Login-Konto bekommen.
-- ==========================================================================

create table if not exists public.mitarbeitende (
  id            bigint generated always as identity primary key,
  auth_user_id  uuid unique references auth.users(id) on delete set null,
  name          text not null,
  email         text,
  aktiv         boolean not null default true
);

-- Etappe 3 (Arbeitsprozess): verfuegbare Fokusstunden pro Woche -- Grundlage fuer die
-- Auslastungsanzeige im Cockpit (Warnung ab 70 % verplant). Pro Person, Standard 15 h.
alter table public.mitarbeitende add column if not exists fokusstunden_woche numeric not null default 15
  check (fokusstunden_woche > 0 and fokusstunden_woche <= 60);

-- Legt bei jeder neuen Supabase-Auth-Anmeldung (nur ueber Dashboard/Admin-API erzeugt, siehe
-- Migrationsplan Phase 2 -- keine oeffentliche Selbstregistrierung) die Verknuepfung zur
-- passenden mitarbeitende-Zeile an: existiert bereits eine Zeile mit derselben E-Mail (z.B.
-- vorher ohne Login angelegt), wird NUR die Verknuepfung ergaenzt (kein Duplikat) -- das
-- entspricht dem bisherigen "Login-Passwort festlegen" fuer eine bestehende Person. Sonst wird
-- eine neue Zeile angelegt. "name" kommt aus den Auth-User-Metadaten (beim Anlegen im
-- Dashboard unter "User Metadata" als {"name": "Angelo"} mitgeben), fehlt es, wird die E-Mail
-- als Platzhalter verwendet.
create or replace function public.handle_new_user()
returns trigger as $$
begin
  update public.mitarbeitende set auth_user_id = new.id
    where email = new.email and auth_user_id is null;
  if not found then
    insert into public.mitarbeitende (auth_user_id, name, email)
    values (new.id, coalesce(new.raw_user_meta_data->>'name', new.email), new.email);
  end if;
  return new;
end;
$$ language plpgsql security definer set search_path = public;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

