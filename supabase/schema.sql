-- ==========================================================================
-- Aggregat-Funktionen -- ersetzen GET /api/pendenzen/cockpit und
-- GET /api/mandanten/uebersicht (backend/src/routes/pendenzen.js bzw. mandanten.js).
-- Als RPC-Funktionen statt Views, damit sie ueber supabase.rpc(...) mit einem Aufruf
-- konsumierbar sind.
