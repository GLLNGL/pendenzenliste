-- --------------------------------------------------------------------------
-- Etappe 4 (Arbeitsprozess) -- wiederkehrende Mandatsarbeiten:
--   typ             Zahlungslauf/Lohnlauf/MWST/Mahnlauf/Jahresabschluss/Sonstiges (steuert die
--                   Standardwerte im Regel-Fenster)
--   block           Block der erzeugten Pendenzen
--   vorlauf_einheit Vorlauf in Kalendertagen oder Arbeitstagen (Zahlungslauf: 2 Arbeitstage)
--   checkliste      Liste von Schritten (JSON-Array aus Texten) -- wird beim Erzeugen als
--                   Projekt-Schritte angelegt (Projekt-Logik aus Etappe 2)
--   prioritaet/harte_frist/aufwand_minuten  Vorgaben fuer die erzeugten Pendenzen
-- Neue Rhythmen "woechentlich" und "14-taeglich" (Zahlungslaeufe).
-- Bestehende Regeln: Typ/Block per Stichwort aus der Titel-Vorlage, sonst "Sonstiges".
-- --------------------------------------------------------------------------

alter table public.wiederkehr_regeln drop constraint if exists wiederkehr_regeln_rhythmus_check;
alter table public.wiederkehr_regeln add constraint wiederkehr_regeln_rhythmus_check
  check (rhythmus in ('woechentlich', '14-taeglich', 'monatlich', 'quartalsweise', 'halbjaehrlich', 'jaehrlich'));

alter table public.wiederkehr_regeln add column if not exists block text not null default 'Sonstiges'
  check (block in ('Zahlungen', 'Lohn', 'MWST', 'Abschluss', 'Debitoren', 'Admin', 'Sonstiges'));
alter table public.wiederkehr_regeln add column if not exists vorlauf_einheit text not null default 'tage'
  check (vorlauf_einheit in ('tage', 'arbeitstage'));
alter table public.wiederkehr_regeln add column if not exists checkliste jsonb not null default '[]'::jsonb;
alter table public.wiederkehr_regeln add column if not exists prioritaet text not null default 'B'
  check (prioritaet in ('A', 'B', 'C'));
alter table public.wiederkehr_regeln add column if not exists harte_frist boolean not null default false;
alter table public.wiederkehr_regeln add column if not exists aufwand_minuten integer
  check (aufwand_minuten in (15, 30, 60, 120));

do $$
begin
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'wiederkehr_regeln' and column_name = 'typ') then
    alter table public.wiederkehr_regeln add column typ text not null default 'Sonstiges'
      check (typ in ('Zahlungslauf', 'Lohnlauf', 'MWST', 'Mahnlauf', 'Jahresabschluss', 'Sonstiges'));
    update public.wiederkehr_regeln set typ = case
        when titel_vorlage ~* '(mwst|mehrwertsteuer)' then 'MWST'
        when titel_vorlage ~* 'lohn' then 'Lohnlauf'
        when titel_vorlage ~* 'zahlung' then 'Zahlungslauf'
        when titel_vorlage ~* 'mahn' then 'Mahnlauf'
        when titel_vorlage ~* '(abschluss|jahresrechnung)' then 'Jahresabschluss'
        else 'Sonstiges'
      end;
    update public.wiederkehr_regeln set block = case typ
        when 'Zahlungslauf' then 'Zahlungen'
        when 'Lohnlauf' then 'Lohn'
        when 'MWST' then 'MWST'
        when 'Mahnlauf' then 'Debitoren'
        when 'Jahresabschluss' then 'Abschluss'
        else 'Sonstiges'
      end;
  end if;
end $$;

