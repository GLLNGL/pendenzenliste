create or replace function public.mandanten_uebersicht()
returns table (
  id bigint, name text, kuerzel text, email text, geschaeftsfuehrung_email text,
  aktiv boolean, notizen text,
  mwst_periode text, lohnzahltag smallint, zahlungslauf_rhythmus text,
  abschluss_wunsch_tag smallint, abschluss_wunsch_monat smallint,
  offene_pendenzen bigint, ueberfaellige_pendenzen bigint
)
language sql
stable
as $$
  select m.id, m.name, m.kuerzel, m.email, m.geschaeftsfuehrung_email, m.aktiv, m.notizen,
    m.mwst_periode, m.lohnzahltag, m.zahlungslauf_rhythmus, m.abschluss_wunsch_tag, m.abschluss_wunsch_monat,
    count(p.id) filter (where p.geplant and p.status != 'Erledigt') as offene_pendenzen,
    count(p.id) filter (where p.geplant and p.status != 'Erledigt' and p.faelligkeit < current_date) as ueberfaellige_pendenzen
  from public.mandanten m
  left join public.pendenzen p on p.mandant_id = m.id
  group by m.id
  order by m.name;
$$;
