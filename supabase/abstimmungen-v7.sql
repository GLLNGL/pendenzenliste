-- ==========================================================================
-- Abstimmungen fuer den Jahresabschluss (v7): MWST und Sozialversicherungen (AHV, BVG, UVG,
-- KTG) pro Mandant und Geschaeftsjahr. Die Eingaben liegen als JSON in "daten" (Aufbau siehe
-- frontend/src/lib/abstimmung.js); Unterlagen liegen im OneDrive-Ordner des Mandanten
-- (Jahresabschluss › Jahr › Bereich), hier nur Name und Pfad. Mehrfach ausfuehrbar.
-- ==========================================================================
create table if not exists public.abstimmungen (
  id             bigint generated by default as identity primary key,
  mandant_id     bigint not null references public.mandanten (id) on delete cascade,
  jahr           smallint not null,
  bereich        text not null check (bereich in ('mwst', 'ahv', 'bvg', 'uvg', 'ktg', 'lohn_grundlagen')),
  status         text not null default 'in_arbeit' check (status in ('in_arbeit', 'abgestimmt', 'entfaellt')),
  daten          jsonb not null default '{}'::jsonb,
  bemerkung      text,
  abgestimmt_am  date,
  geaendert_am   timestamptz not null default now(),
  unique (mandant_id, jahr, bereich)
);
create index if not exists idx_abstimmungen_jahr_bereich on public.abstimmungen (jahr, bereich);

alter table public.abstimmungen enable row level security;
drop policy if exists team_voller_zugriff on public.abstimmungen;
create policy team_voller_zugriff on public.abstimmungen
  for all using (auth.uid() is not null) with check (auth.uid() is not null);
