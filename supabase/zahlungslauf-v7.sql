-- ==========================================================================
-- Zahlungslauf (v7): aus offenen Kreditorenrechnungen eine Zahlungsdatei pain.001 erstellen.
-- Der Lauf merkt sich Datum, Summe und die Datei (zum erneuten Herunterladen); die Belege
-- zeigen auf ihren Lauf, bis sie als bezahlt markiert sind. Mehrfach ausfuehrbar.
-- ==========================================================================
create table if not exists public.zahlungslaeufe (
  id                 bigint generated by default as identity primary key,
  ausfuehrungsdatum  date not null,
  anzahl             integer not null,
  summe              numeric(12, 2) not null,
  msg_id             text not null unique,
  dateiname          text not null,
  datei_xml          text not null,
  bezahlt_am         date,
  erstellt_am        timestamptz not null default now()
);

alter table public.belege add column if not exists zahlungslauf_id bigint references public.zahlungslaeufe(id) on delete set null;

alter table public.zahlungslaeufe enable row level security;
drop policy if exists team_voller_zugriff on public.zahlungslaeufe;
create policy team_voller_zugriff on public.zahlungslaeufe
  for all using (auth.uid() is not null) with check (auth.uid() is not null);
